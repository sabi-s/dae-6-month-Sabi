"""
RSA key pair management for HVMC: protected storage, fingerprints, a key inventory
with cryptoperiods, hybrid (envelope) encryption, and key rotation.

Horizon Valley Medical Center (HVMC) - Cryptography 1: Utilize Public Key Cryptography
Author: Sabitha S Karanavar

Keys are generated by the from-scratch generator in rsa.py and stored by the
`cryptography` package as encrypted PKCS #8 PEM files (passphrase-protected,
file mode 0600). In production the same roles map to Azure Key Vault / an HSM.
"""
import base64
import datetime as dt
import hashlib
import json
import os
import secrets

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

import rsa

UTC = dt.timezone.utc

# HVMC key policy, based on NIST SP 800-57 Part 1 Rev. 5 (section 5.6, table 2: RSA-2048 = 112-bit
# security, acceptable through 2030; RSA-3072 = 128-bit). Cryptoperiods follow section 5.3.6.
POLICY = {
    "root-ca":         {"bits": 4096, "days": 3650, "storage": "offline, encrypted (HSM in production)"},
    "issuing-ca":      {"bits": 3072, "days": 1825, "storage": "encrypted, CA host only"},
    "tls-server":      {"bits": 2048, "days": 397,  "storage": "encrypted, web server only"},
    "client-auth":     {"bits": 2048, "days": 365,  "storage": "encrypted, user device"},
    "data-encryption": {"bits": 3072, "days": 730,  "storage": "encrypted, EHR key service"},
}


class KeyPolicyError(Exception):
    pass


def fingerprint(public_key):
    """SHA-256 of the DER SubjectPublicKeyInfo - the same value used for certificate
    and SSH key pinning. Identifies a key without revealing anything secret."""
    der = public_key.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    return hashlib.sha256(der).hexdigest()


def save_private_key(lib_key, path, passphrase):
    """Encrypted PKCS #8 ('BEGIN ENCRYPTED PRIVATE KEY'). The file is created with mode 0600
    so other local accounts cannot read it, even though the contents are encrypted."""
    pem = lib_key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                serialization.BestAvailableEncryption(passphrase))
    os.makedirs(os.path.dirname(path), mode=0o700, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(pem)


def load_private_key(path, passphrase):
    with open(path, "rb") as f:
        return serialization.load_pem_private_key(f.read(), password=passphrase)


def save_public_key(lib_key, path):
    pem = lib_key.public_key().public_bytes(serialization.Encoding.PEM,
                                            serialization.PublicFormat.SubjectPublicKeyInfo)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(pem)


def get_passphrase(private_dir):
    """Passphrase from the HVMC_PKI_PASSPHRASE environment variable, or a random one kept in
    private/.passphrase (mode 0600, never committed). Production: a Key Vault secret."""
    env = os.environ.get("HVMC_PKI_PASSPHRASE")
    if env:
        return env.encode()
    path = os.path.join(private_dir, ".passphrase")
    if os.path.exists(path):
        with open(path, "rb") as f:
            return f.read().strip()
    os.makedirs(private_dir, mode=0o700, exist_ok=True)
    value = secrets.token_urlsafe(32).encode()
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(value + b"\n")      # OpenSSL's -passin file: reads one line
    return value


class KeyStore:
    """A key inventory: every key pair has an ID, purpose, owner, fingerprint, created and
    expiry dates, and a status. Status moves one way only:
        active -> retired (decrypt/verify only) -> destroyed
        active -> compromised (revoked immediately)"""

    def __init__(self, root, passphrase):
        self.root, self.passphrase = root, passphrase
        self.private_dir = os.path.join(root, "private")
        self.inventory_path = os.path.join(root, "key_inventory.json")
        self.keys = {}
        if os.path.exists(self.inventory_path):
            with open(self.inventory_path) as f:
                self.keys = {k["key_id"]: k for k in json.load(f)}

    def _save(self):
        with open(self.inventory_path, "w") as f:
            json.dump(list(self.keys.values()), f, indent=2)

    def generate(self, key_id, purpose, owner, now=None):
        if purpose not in POLICY:
            raise KeyPolicyError(f"unknown purpose {purpose}")
        if key_id in self.keys and self.keys[key_id]["status"] != "destroyed":
            raise KeyPolicyError(f"{key_id} already exists")
        pol = POLICY[purpose]
        now = now or dt.datetime.now(UTC)
        scratch = rsa.generate_keypair(pol["bits"])          # from-scratch generation
        lib_key = rsa.to_library(scratch)                    # the library accepts it as a valid key
        save_private_key(lib_key, os.path.join(self.private_dir, f"{key_id}.key.pem"), self.passphrase)
        save_public_key(lib_key, os.path.join(self.root, "public", f"{key_id}.pub.pem"))
        self.keys[key_id] = {
            "key_id": key_id, "purpose": purpose, "owner": owner, "algorithm": f"RSA-{pol['bits']}",
            "public_exponent": scratch.e, "fingerprint_sha256": fingerprint(lib_key.public_key()),
            "created": now.isoformat(timespec="seconds"),
            "expires": (now + dt.timedelta(days=pol["days"])).isoformat(timespec="seconds"),
            "status": "active", "storage": pol["storage"],
            "private_key_file": f"private/{key_id}.key.pem", "public_key_file": f"public/{key_id}.pub.pem",
            "history": [f"{now.date()} generated"],
        }
        self._save()
        return lib_key

    def private(self, key_id):
        return load_private_key(os.path.join(self.private_dir, f"{key_id}.key.pem"), self.passphrase)

    def public(self, key_id):
        with open(os.path.join(self.root, "public", f"{key_id}.pub.pem"), "rb") as f:
            return serialization.load_pem_public_key(f.read())

    def require(self, key_id, use, now=None):
        """Enforce the key policy before every use."""
        rec = self.keys[key_id]
        now = now or dt.datetime.now(UTC)
        if use == "encrypt":
            if rec["status"] != "active":
                raise KeyPolicyError(f"{key_id} is {rec['status']}: new encryption not allowed")
            if now > dt.datetime.fromisoformat(rec["expires"]):
                raise KeyPolicyError(f"{key_id} expired on {rec['expires'][:10]}")
        elif use == "decrypt" and rec["status"] not in ("active", "retired"):
            raise KeyPolicyError(f"{key_id} is {rec['status']}: no longer usable")
        return rec

    def set_status(self, key_id, status, note, now=None):
        now = now or dt.datetime.now(UTC)
        rec = self.keys[key_id]
        rec["status"] = status
        rec["history"].append(f"{now.date()} {status}: {note}")
        if status == "destroyed":
            path = os.path.join(self.private_dir, f"{key_id}.key.pem")
            if os.path.exists(path):
                os.remove(path)          # on an SSD/HSM this is a crypto-erase; here, a delete
        self._save()


# ---------------------------------------------------------------- hybrid (envelope) encryption
def _b64(b):
    return base64.b64encode(b).decode()


def hybrid_encrypt(store, key_id, plaintext, aad=b""):
    """RSA is slow and can only encrypt k - 66 bytes (190 bytes for RSA-2048 with OAEP-SHA-256),
    so HVMC encrypts the record with a random AES-256-GCM data key and wraps only that 32-byte
    key with RSA-OAEP (the from-scratch implementation)."""
    store.require(key_id, "encrypt")
    pub = rsa.from_library_public(store.public(key_id))
    dek = AESGCM.generate_key(256)
    nonce = secrets.token_bytes(12)
    return {
        "key_id": key_id, "alg": "RSA-OAEP-256 + A256GCM",
        "wrapped_key": _b64(rsa.oaep_encrypt(pub, dek, label=key_id.encode())),
        "nonce": _b64(nonce), "aad": _b64(aad),
        "ciphertext": _b64(AESGCM(dek).encrypt(nonce, plaintext, aad)),
    }


def _unwrap(store, env):
    store.require(env["key_id"], "decrypt")
    nums = store.private(env["key_id"]).private_numbers()
    priv = rsa.RSAPrivateKey(nums.p, nums.q, nums.public_numbers.e)
    return rsa.oaep_decrypt(priv, base64.b64decode(env["wrapped_key"]), label=env["key_id"].encode())


def hybrid_decrypt(store, env):
    dek = _unwrap(store, env)
    return AESGCM(dek).decrypt(base64.b64decode(env["nonce"]), base64.b64decode(env["ciphertext"]),
                               base64.b64decode(env["aad"]))


def rewrap(store, env, new_key_id):
    """Key rotation without touching the bulk data: unwrap the data key with the old
    RSA key and wrap it again with the new one. The AES ciphertext is unchanged."""
    dek = _unwrap(store, env)
    store.require(new_key_id, "encrypt")
    pub = rsa.from_library_public(store.public(new_key_id))
    out = dict(env)
    out["key_id"] = new_key_id
    out["wrapped_key"] = _b64(rsa.oaep_encrypt(pub, dek, label=new_key_id.encode()))
    return out
